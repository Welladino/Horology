"""Execution history: agent runs, copies of the Pipeline records, status events and run outputs.

The founder edits Sheets; this is the machine history behind them.
- run_log (created 2026-08-05, never used) becomes the agent-run table: one
  row per run, created by the claim_item tool (an atomic 2-hour claim) and
  closed by finish_run. Skills used, steps done and notes are self-reported.
- pipeline_items, decisions, document_index: copies of Pipeline Master, the
  Decision Register and the Document Index, written by the sync job's
  records pass. document_index holds every row's details (no content);
  documents still holds only the rows included in the knowledge graph.
- pipeline_events: changes the records pass sees between two copies,
  attributed to a run of that item active in between, if any.
- run_outputs: what each run produced: Document Index rows and agent
  documents for its item during the run, linked by the records pass.
Everything is scoped by workspace. graph_runs gains the 'records' mode.
"""
