import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const shared = path.dirname(fileURLToPath(import.meta.url));
const root = path.dirname(shared);
const name = process.argv[2];
const check = process.argv.includes('--check');
if (!['pipeline-decisions', 'pipeline-locations'].includes(name)) {
  throw Error('Usage: node shared-ui/build.mjs pipeline-decisions|pipeline-locations [--check]');
}
const css = ['theme.css', 'controls.css'].map(file =>
  fs.readFileSync(path.join(shared, file), 'utf8').trimEnd()).join('\n\n');
const js = fs.readFileSync(path.join(shared, 'components.js'), 'utf8').trimEnd();
const output = '<!-- Generated by google_appscript/shared-ui/build.mjs; edit shared-ui sources. -->\n' +
  '<style>\n' + css + '\n</style>\n<script>\n' + js + '\n</script>\n';
const target = path.join(root, name, 'src', 'SharedUi.html');
if (check) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output)
    throw Error(name + '/src/SharedUi.html is stale. Run npm run ui:build.');
  console.log(name + ' shared UI is current');
} else {
  fs.writeFileSync(target, output);
  console.log('Built ' + target);
}
